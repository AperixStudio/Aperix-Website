/** Stable id for `/our-work#…` links. Shared with the services hub. */
export function caseStudyId(name: string) {
  return name
    .toLowerCase()
    .replace(/['’]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

